#!/usr/bin/env node
/**
 * Propagates `app.config.json` to every place the product name has to be a
 * literal.
 *
 * Several of them cannot read a shared constant, which is the whole reason this
 * script exists:
 *
 *   - **Android's manifest** is XML read by the OS before any Dart runs, so the
 *     label goes through a string resource.
 *   - **iOS's Info.plist** is likewise read by the OS. Three keys carry the name:
 *     `CFBundleDisplayName` (under the icon), `CFBundleName` (the short name iOS
 *     falls back to, and what Xcode shows in an archive), and
 *     `NSCameraUsageDescription` — the permission sheet, which names the app to
 *     the student out loud and is reviewed by Apple.
 *   - **`pubspec.yaml`'s description** is package metadata, not code.
 *   - **Dart** and **TypeScript** could share a constant within themselves but
 *     not with each other, so each gets a generated file.
 *
 * Adding a place here is cheap; forgetting one is not. `CFBundleName` and the
 * camera string were both missed on the first two renames and kept a dead brand
 * alive in the archive Xcode showed and in the permission prompt a student
 * would have read. `tests/unit/app-identity.test.ts` now fails when any of
 * these drifts from `app.config.json`.
 *
 * Generated files are marked as such and must not be hand-edited — the next run
 * overwrites them.
 *
 * The bundle id is behind an explicit `--bundle-id` flag rather than running
 * with every rename. It is permanent once published — both stores identify an
 * app by it forever, and Apple requires the new one to be registered in the
 * developer portal before a build using it will upload — so changing it has to
 * be a decision, not a side effect of trying a different display name.
 */
import { mkdirSync, readFileSync, rmSync, rmdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(readFileSync(join(root, "app.config.json"), "utf8"));

const { name, supportEmail, tagline } = config;
if (!name || typeof name !== "string") {
  console.error("app.config.json needs a non-empty `name`.");
  process.exit(1);
}

// `CFBundleName` is documented as no more than 15 characters; iOS truncates
// past that rather than erroring, so a long name would silently ship clipped.
if (name.length > 15) {
  console.error(`\`name\` must be 15 characters or fewer for CFBundleName: ${name}`);
  process.exit(1);
}

// The name reaches XML and a plist, so a stray quote or angle bracket would
// produce a file that no longer parses — and on Android that is a build the
// store rejects rather than an error you see locally.
if (/["'<>&]/.test(name)) {
  console.error(`\`name\` must not contain quotes or angle brackets: ${name}`);
  process.exit(1);
}

const applyBundleId = process.argv.includes("--bundle-id");
const written = [];

function write(path, contents) {
  writeFileSync(join(root, path), contents);
  written.push(path);
}

// --- Dart ------------------------------------------------------------------
write(
  "mobile/lib/src/core/app_info.dart",
  `// GENERATED by scripts/apply-app-identity.mjs — do not edit.
// Change the name in app.config.json and run \`npm run app:name\`.

/// The product's name, as shown inside the app.
///
/// Separate from the store listing title, which must be globally unique and is
/// therefore often longer. This is what a student reads on the sign-in screen.
class AppInfo {
  const AppInfo._();

  static const String name = ${JSON.stringify(name)};
  static const String supportEmail = ${JSON.stringify(supportEmail ?? "")};
}
`,
);

// --- TypeScript ------------------------------------------------------------
write(
  "src/lib/app-info.ts",
  `// GENERATED by scripts/apply-app-identity.mjs — do not edit.
// Change the name in app.config.json and run \`npm run app:name\`.

/** The product's name, as shown in the web console and page titles. */
export const APP_NAME = ${JSON.stringify(name)};

export const SUPPORT_EMAIL = ${JSON.stringify(supportEmail ?? "")};

/** \`Students · <app name>\` — the shape every page title takes. */
export const pageTitle = (section: string) => \`\${section} · \${APP_NAME}\`;
`,
);

// --- Android ---------------------------------------------------------------
// A string resource rather than a literal in the manifest, which is Android's
// own answer to this problem and keeps the manifest free of the product name.
write(
  "mobile/android/app/src/main/res/values/strings.xml",
  `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/apply-app-identity.mjs — do not edit. -->
<resources>
    <string name="app_name">${name}</string>
</resources>
`,
);

// --- iOS -------------------------------------------------------------------
// PlistBuddy rather than a text replace: Info.plist is XML that Xcode rewrites,
// and editing it as text is how it eventually stops parsing.
const plist = join(root, "mobile/ios/Runner/Info.plist");
const plistEntries = {
  CFBundleDisplayName: name,
  CFBundleName: name,
  // Apple rejects a vague purpose string, and the student reads it verbatim on
  // the permission sheet — so it names the app and says what it scans.
  NSCameraUsageDescription: `${name} uses the camera to scan students' meal codes at the counter.`,
};
// `plutil`, not PlistBuddy. PlistBuddy re-parses everything after `Set :key `
// as its own little command line, and there is no escaping that survives it —
// the apostrophe in "students' meal codes" is an unclosed quote however it is
// quoted, and the run dies part-applied, leaving two keys renamed and one on
// the old brand. `plutil -replace` takes the value as a real argument.
for (const [key, value] of Object.entries(plistEntries)) {
  execFileSync("plutil", ["-replace", key, "-string", value, plist]);
}
written.push(`mobile/ios/Runner/Info.plist (${Object.keys(plistEntries).join(", ")})`);

// --- Flutter package metadata ----------------------------------------------
const pubspecFile = join(root, "mobile/pubspec.yaml");
writeFileSync(
  pubspecFile,
  readFileSync(pubspecFile, "utf8").replace(
    /^description: .*$/m,
    `description: ${JSON.stringify(`${name} — ${tagline ?? ""}`.trim())}`,
  ),
);
written.push("mobile/pubspec.yaml (description)");

// --- Bundle id, on request only ---------------------------------------------
if (applyBundleId) {
  const bundleId = config.bundleId;
  if (!/^[a-z0-9]+(\.[a-z0-9]+)+$/.test(bundleId ?? "")) {
    console.error(`\`bundleId\` must be reverse-DNS and lowercase: ${bundleId}`);
    process.exit(1);
  }

  const gradle = join(root, "mobile/android/app/build.gradle.kts");
  let g = readFileSync(gradle, "utf8");
  g = g.replace(/namespace = "[^"]+"/, `namespace = "${bundleId}"`);
  g = g.replace(/applicationId = "[^"]+"/, `applicationId = "${bundleId}"`);
  writeFileSync(gradle, g);
  written.push("mobile/android/app/build.gradle.kts");

  // Kotlin's package must match the directory it lives in, so the file moves.
  const kotlinRoot = join(root, "mobile/android/app/src/main/kotlin");
  const dest = join(kotlinRoot, ...bundleId.split("."));
  const found = execFileSync("find", [kotlinRoot, "-name", "MainActivity.kt"], {
    encoding: "utf8",
  })
    .trim()
    .split("\n")
    .filter(Boolean);

  for (const from of found) {
    mkdirSync(dest, { recursive: true });
    const body = readFileSync(from, "utf8").replace(/^package .+$/m, `package ${bundleId}`);
    writeFileSync(join(dest, "MainActivity.kt"), body);
    if (from !== join(dest, "MainActivity.kt")) {
      rmSync(from);
      // Prune the directories the old package left behind. Kotlin infers
      // nothing from an empty folder, but a tree littered with dead package
      // paths is how the next person guesses the wrong one.
      let dir = dirname(from);
      while (dir.startsWith(kotlinRoot) && dir !== kotlinRoot) {
        try {
          rmdirSync(dir);
        } catch {
          break; // not empty — something else lives here
        }
        dir = dirname(dir);
      }
    }
  }
  written.push("mobile/android/.../MainActivity.kt");

  // The Dart and npm package names follow the bundle id's middle segment —
  // `com.mealadda.app` gives `mealadda`. They are internal, but leaving them on
  // a dead brand means every import in the repo names a product that no longer
  // exists, and doing it by hand each rename is how that drift happens.
  const pkg = bundleId.split(".").at(-2);
  if (pkg) {
    const dartFiles = execFileSync(
      "find",
      [join(root, "mobile/lib"), join(root, "mobile/test"), "-name", "*.dart"],
      { encoding: "utf8" },
    )
      .trim()
      .split("\n")
      .filter(Boolean);

    // Only OUR package. A blanket `package:*/` rewrite also hits every
    // dependency — `package:intl/` and `package:flutter_riverpod/` become the
    // app's own name and nothing compiles. The current name comes from
    // pubspec, which is the only place that knows it.
    const pubspecPath = join(root, "mobile/pubspec.yaml");
    const pubspec = readFileSync(pubspecPath, "utf8");
    const currentPkg = /^name:\s*([a-z0-9_]+)$/m.exec(pubspec)?.[1];

    if (currentPkg && currentPkg !== pkg) {
      const from = new RegExp(`package:${currentPkg}/`, "g");
      for (const f of dartFiles) {
        const before = readFileSync(f, "utf8");
        const after = before.replace(from, `package:${pkg}/`);
        if (after !== before) writeFileSync(f, after);
      }
      writeFileSync(pubspecPath, pubspec.replace(/^name:\s*[a-z0-9_]+$/m, `name: ${pkg}`));
    }

    const pkgJson = join(root, "package.json");
    writeFileSync(
      pkgJson,
      readFileSync(pkgJson, "utf8").replace(/"name": "[^"]+"/, `"name": "${pkg}"`),
    );
    written.push(`Dart + npm package name (${pkg})`);
  }

  const pbx = join(root, "mobile/ios/Runner.xcodeproj/project.pbxproj");
  // The test target's id is conventionally the app's plus a suffix, so it has
  // to follow rather than be left on the old prefix.
  const p = readFileSync(pbx, "utf8").replace(
    /PRODUCT_BUNDLE_IDENTIFIER = ([^;]+);/g,
    (_, current) =>
      `PRODUCT_BUNDLE_IDENTIFIER = ${
        current.trim().endsWith(".RunnerTests") ? `${bundleId}.RunnerTests` : bundleId
      };`,
  );
  writeFileSync(pbx, p);
  written.push("mobile/ios/Runner.xcodeproj (PRODUCT_BUNDLE_IDENTIFIER)");

  console.log(
    `\n⚠️  Bundle id set to ${bundleId}. Register it at`,
    "\n    developer.apple.com → Identifiers → App IDs, or the next upload is refused.\n",
  );
}

console.log(`App name set to "${name}" in:`);
for (const path of written) console.log(`  ${path}`);
console.log(
  "\nThe App Store and Play listing titles are set in their consoles by hand —\n" +
    "they must be globally unique and are often longer than this.",
);
